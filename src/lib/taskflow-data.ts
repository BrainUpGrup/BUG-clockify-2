/**
 * Obtiene los elementos de TaskFlow sincronizados con localStorage o con las semillas por defecto.
 */
export function getStoredTaskFlowItems(): TaskFlowItem[] {
  if (typeof window === 'undefined') return SEED_TASKFLOW_ITEMS;
  try {
    const stored = localStorage.getItem(STORAGE_KEY_ITEMS_V2);
    if (stored) {
      const parsed = JSON.parse(stored);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
    // Inicializar semillas si no existían
    localStorage.setItem(STORAGE_KEY_ITEMS_V2, JSON.stringify(SEED_TASKFLOW_ITEMS));
    return SEED_TASKFLOW_ITEMS;
  } catch (e) {
    console.warn('Error al leer TaskFlow items:', e);
    return SEED_TASKFLOW_ITEMS;
  }
}

/**
 * Filtra los entregables y reuniones pendientes de una empresa para los próximos N días.
 */
export function getUpcomingDeliverablesForCompany(
  items: TaskFlowItem[],
  companyId: string,
  companyName: string,
  daysAhead: number = 15
): TaskFlowItem[] {
  if (!items || !items.length) return [];

  const todayStr = new Date().toISOString().split('T')[0];
  const maxDate = new Date();
  maxDate.setDate(maxDate.getDate() + daysAhead);
  const maxDateStr = maxDate.toISOString().split('T')[0];

  const targetName = (companyName || '').trim().toLowerCase();

  return items
    .filter((it) => {
      // 1. Descartar finalizadas
      if (it.status === 'done') return false;

      // 2. Coincidencia de empresa por ID o por nombre
      const idMatch = Boolean(it.companyId && companyId && it.companyId === companyId);
      const itName = (it.companyName || '').trim().toLowerCase();
      const nameMatch = Boolean(
        targetName && itName && (
          itName === targetName ||
          itName.includes(targetName) ||
          targetName.includes(itName)
        )
      );

      if (!idMatch && !nameMatch) return false;

      // 3. Ventana temporal: tareas de hasta N días en el futuro (o anteriores aún pendientes)
      return it.date <= maxDateStr;
    })
    .sort((a, b) => a.date.localeCompare(b.date));
}
